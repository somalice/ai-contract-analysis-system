_add('付款协议质保金与违约金', 'contract', """\
付款协议质保金与违约金

一、质保金条款
质保金（质量保证金）用于约束收款方在质保期内履行质量义务，防止交付后逃避责任。
质保金比例通常为合同总价的5%-10%。质保期一般为6个月至2年（按行业和产品特性）。
质保期满无质量问题则无息退还质保金。

二、逾期付款违约金
逾期付款违约金通常按日计算：每日万分之三至万分之五（年利率约10.95%-18.25%），
同时设置上限（通常不超过未付款总额的5%-10%）。
违约金过分高于实际损失时，法院可依《民法典》第585条酌情调减，故应在合理区间内。

三、逾期交货/服务违约金
收款方逾期交付的违约金通常为每日合同总额的万分之三至千分之一，
设置上限（通常不超过合同总额的5%-10%）。逾期超过约定期限，付款方可解除合同。

四、违约金与赔偿金关系
违约金是预先约定的违约赔偿数额。约定违约金低于实际损失的可请求增加，
过分高于实际损失的可请求适当减少。违约金与赔偿金一般不重复主张，以实际损失为基准调整。

五、付款担保
大额付款协议可约定担保：
1. 保证：第三方保证人承担连带/一般保证责任；
2. 抵押：以不动产或动产设定抵押权；
3. 质押：以动产或权利设定质权；
4. 定金：不超过主合同标的额20%，给付方违约不返还，收受方违约双倍返还。

六、抵销与抗辩
付款方享有同时履行抗辩权、先履行抗辩权、不安抗辩权。
双方互负到期债务的，可约定抵销。付款方对收款方主张的质量、交付异议可作付款抗辩。
""")

